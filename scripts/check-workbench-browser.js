async page => {

  const checks = []; const {base,id} = await page.evaluate(()=>({base:location.origin,id:new URL(location.href).searchParams.get('task')}))
  const get = async suffix => (await page.request.get(base + '/api/retrieval-agent/tasks/' + id + suffix)).json()
  const before = await get(''), assert = (ok, name) => { checks.push({ name, passed: !!ok }); if (!ok) throw new Error(name) }
  try {
    assert(before.node.collectionWindow.confirmed === 1, 'fixture confirms exactly one after answer and optional mistaken feedback')
    assert(before.feedback.at(-1).status === 'reviewed', 'feedback has durable model disposition')
    await page.getByRole('tab', {name:'工单结果',exact:true}).click()
    await page.getByRole('button',{name:'查看依据 ↗'}).waitFor()
    assert(await page.locator('#cards .ticket-id').allTextContents().then(ids=>ids.join()==='T-2'), 'main list is confirmed T-2 without manual approval')
    await page.getByRole('tab',{name:'检索报告',exact:true}).click()
    await page.getByRole('button',{name:'打开对应原文',exact:true}).first().waitFor()
    await page.getByRole('button',{name:'打开对应原文',exact:true}).first().scrollIntoViewIfNeeded()
    const reportTop = await page.evaluate(()=>window.scrollY)
    await page.getByRole('button',{name:'打开对应原文',exact:true}).first().click()
    await page.locator('#detail mark').first().waitFor()
    assert((await page.locator('#detail').innerText()).includes('重新同步解绑状态后恢复'), 'report reference opens actual controlled full source')
    await page.keyboard.press('Escape')
    assert(await page.getByRole('button',{name:'打开对应原文',exact:true}).first().evaluate(el=>el===document.activeElement), 'Escape restores report citation focus')
    assert(Math.abs(await page.evaluate(()=>window.scrollY)-reportTop)<=2, 'closing evidence restores report reading position')
    await page.getByRole('button',{name:'生成报告',exact:true}).click()
    const reportRow = page.locator('#artifacts .card').filter({hasText:'工作人员报告'})
    await reportRow.getByRole('button',{name:'保存 工作人员报告',exact:true}).waitFor({timeout:30000})
    const reportDownload = page.waitForEvent('download'); await reportRow.getByRole('button',{name:'保存 工作人员报告',exact:true}).click()
    await (await reportDownload).saveAs('output/phase8/fixture-report.md')
    await page.getByRole('button',{name:'生成 CSV',exact:true}).click()
    const csv = page.locator('#artifacts .card').filter({hasText:'CSV'})
    await csv.getByRole('button',{name:'保存 CSV',exact:true}).waitFor({timeout:30000})
    const csvDownload = page.waitForEvent('download'); await csv.getByRole('button',{name:'保存 CSV',exact:true}).click()
    await (await csvDownload).saveAs('output/phase8/fixture.csv')
    await page.getByRole('combobox',{name:'文件内容'}).selectOption('full')
    await page.getByRole('button',{name:'生成 JSONL',exact:true}).click()
    const jsonl = page.locator('#artifacts .card').filter({hasText:'JSONL'})
    await jsonl.getByRole('button',{name:'保存 JSONL',exact:true}).waitFor({timeout:30000})
    const jsonDownload = page.waitForEvent('download'); await jsonl.getByRole('button',{name:'保存 JSONL',exact:true}).click()
    await (await jsonDownload).saveAs('output/phase8/fixture.jsonl')
    const manifestDownload = page.waitForEvent('download'); await jsonl.getByRole('button',{name:'保存范围说明',exact:true}).click()
    await (await manifestDownload).saveAs('output/phase8/fixture-manifest.json')
    const artifactList = await get('/artifacts'); const artifact = artifactList.find(d=>d.kind==='jsonl'&&d.status==='ready'); const rows = (await (await page.request.get(base+'/api/retrieval-agent/tasks/'+id+'/artifacts/'+artifact.id+'/content')).text()).trim().split('\n').map(JSON.parse)
    assert(rows.length === 1 && rows[0].ticketId === 'T-2' && rows[0].resultRevision === before.node.result.resultRevision, 'downloaded file set and result revision agree')
    assert(rows[0].fields.resolutionSteps[0].includes('恢复'), 'full template preserves source fields')
    const manifest = await get('/artifacts/'+artifact.id+'/manifest')
    assert(manifest.rowCount === 1 && manifest.resultRevision === rows[0].resultRevision, 'manifest matches complete confirmed file')
    await page.locator('#close-delivery').click()
    await page.getByRole('tab',{name:'工单结果',exact:true}).click()
    await page.getByRole('button',{name:'查看依据 ↗'}).waitFor()
    for (const width of [1440,1024,736,360]) {
      await page.setViewportSize({width,height:900})
      await page.getByRole('button',{name:'查看依据 ↗'}).click(); await page.locator('#detail mark').first().waitFor()
      assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'no horizontal overflow with evidence at ' + width)
      await page.screenshot({path:'output/playwright/phase8-fixture-evidence-'+width+'.png',fullPage:true})
      await page.keyboard.press('Escape')
      assert(await page.getByRole('button',{name:'查看依据 ↗'}).evaluate(el=>el===document.activeElement), 'evidence focus returns at '+width)
    }
    const second = await page.context().newPage(); let posts = 0
    second.on('request', r => { if(r.method()==='POST') posts++ })
    await second.goto(page.url()); await second.locator('#cards .ticket-id').waitFor()
    assert((await second.locator('#cards .ticket-id').innerText()) === 'T-2' && posts === 0, 'second tab restores same task without submitting work')
    await second.close(); await page.reload(); await page.locator('#cards .ticket-id').waitFor()
    assert((await get('')).inputRevision === before.inputRevision, 'refresh retains input revision')
    await page.context().setOffline(true)
    await page.context().setOffline(false)
    await page.locator('#cards .ticket-id').waitFor()
    assert((await get('')).commands.length === before.commands.length, 'reconnect submits no duplicate command')
    await page.getByRole('tab',{name:'工单结果',exact:true}).focus(); await page.keyboard.press('ArrowRight')
    assert(await page.getByRole('tab',{name:'检索过程',exact:true}).getAttribute('aria-selected') === 'true', 'keyboard tab navigation')
    await page.keyboard.press('ArrowRight'); await page.getByRole('button',{name:'打开对应原文',exact:true}).first().waitFor()
    for (const width of [1440,1024,736,360]) {
      await page.setViewportSize({width,height:900})
      assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'report and long hash fit at '+width)
    }
    await page.screenshot({path:'output/playwright/phase8-fixture-report-360.png',fullPage:true})
  } catch (e) { return {taskId:id,checks,error:String(e)} } return {taskId:id,checks}
}
